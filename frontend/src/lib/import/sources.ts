export function getImportSource(id: string | undefined): ImportSource {
  return IMPORT_SOURCES.find((s) => s.id === id) || IMPORT_SOURCES[0];
}

/** The source that matches an auto-detected format (used when a dropped file is not what the source expected). */
export function sourceForFormat(format: ImportFormat): ImportSource {
  if (format === "sql" || format === "auto") return IMPORT_SOURCES[0];
  return IMPORT_SOURCES.find((s) => s.id === format) || IMPORT_SOURCES[0];
}

export interface ImportAnalysis {
  empty: boolean;
  result: ImportResult | null;
  /** What the text looks like, regardless of the selected source. */
  detected: Exclude<ImportFormat, "auto"> | null;
  /** Human label of what will be imported, e.g. "PostgreSQL" or "Prisma schema". */
  label: string;
  /** The chosen source failed while the text looks like a different format. */
  mismatch: boolean;
}

/** Runs the importer for the selected source and summarises the outcome (used for the live summary line). */
export function analyzeImport(text: string, source: ImportSource, filename?: string): ImportAnalysis {
  if (!text.trim()) return { empty: true, result: null, detected: null, label: "", mismatch: false };
  const detected = detectFormat(text, filename);
  const format: ImportFormat = source.format === "auto" ? detected : source.format;
  const result = importText(text, format, { filename, dialect: source.dialect });
  const failed = result.errors.length > 0;
  const mismatch = source.format !== "auto" && detected !== source.format && failed;
  let label: string;
  if (result.format === "sql") label = SQL_DIALECTS.find((d) => d.id === (result.dialect ?? source.dialect))?.label || "SQL";
  else label = IMPORT_FORMATS.find((f) => f.id === result.format)?.label || result.format;
  return { empty: false, result, detected, label, mismatch };
}
