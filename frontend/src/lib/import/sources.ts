export type InstructionBlock =
  | { kind: "text"; text: string }
  /** `shell` puts a "$" prompt in front (terminal command); placeholders are written as <name>. */
  | { kind: "code"; code: string; shell?: boolean };

export interface ImportSource {
  id: string;
  label: string;
  group: "auto" | "database" | "file" | "data";
  /** Which importer runs. "auto" detects the format from the text. */
  format: ImportFormat;
  /** SQL dialect the parser should expect (database sources only). */
  dialect?: SqlDialect;
  /** Heading of the instructions pane. */
  title: string;
  blocks: InstructionBlock[];
  /** `accept` attribute of the file picker. */
  accept: string;
  placeholder: string;
}

